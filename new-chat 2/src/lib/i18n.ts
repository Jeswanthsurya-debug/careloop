/**
 * UI strings for a language tag.
 *
 * Any key missing from a translation falls back to English rather than
 * rendering blank, so a partial translation can never break the screen.
 */
export function ui(lang: string): UiStrings {
  const code = resolveLang(lang).code;
  const base = UI["en-US"];
  const chosen = UI[code];
  if (!chosen) return base;

  const merged = { ...base, ...chosen } as UiStrings;
  // Nested objects need the same treatment.
  merged.states = { ...base.states, ...(chosen.states ?? {}) };
  merged.suggestions = (chosen.suggestions ?? base.suggestions) as [string, string, string];
  return merged;
}
